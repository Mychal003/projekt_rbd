CREATE TABLE kategorie (
  id_kategorii NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nazwa        VARCHAR2(100 CHAR) NOT NULL UNIQUE
);

CREATE TABLE typy_produktow (
  id_produktu  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nazwa        VARCHAR2(200 CHAR) NOT NULL,
  id_kategorii NUMBER NOT NULL REFERENCES kategorie(id_kategorii),
  opis         VARCHAR2(500 CHAR),
  aktywny      NUMBER(1) DEFAULT 1 NOT NULL CHECK (aktywny IN (0,1))
);

CREATE TABLE stany_magazynowe (
  id_produktu         NUMBER PRIMARY KEY REFERENCES typy_produktow(id_produktu),
  sklep               CHAR(3) DEFAULT 'WRO' NOT NULL CHECK (sklep = 'WRO'),
  cena                NUMBER(10,2) NOT NULL CHECK (cena >= 0),
  ilosc_dostepna      NUMBER DEFAULT 0 NOT NULL CHECK (ilosc_dostepna >= 0),
  ilosc_zarezerwowana NUMBER DEFAULT 0 NOT NULL CHECK (ilosc_zarezerwowana >= 0),
  data_modyfikacji    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE OR REPLACE TRIGGER trg_stany_mod
BEFORE UPDATE ON stany_magazynowe FOR EACH ROW
BEGIN
  :NEW.data_modyfikacji := SYSTIMESTAMP;
END;
/

CREATE TABLE zamowienia (
  id_zamowienia   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sklep           CHAR(3) DEFAULT 'WRO' NOT NULL CHECK (sklep = 'WRO'),
  data_zamowienia DATE DEFAULT SYSDATE NOT NULL,
  status          VARCHAR2(20) DEFAULT 'NOWE' NOT NULL
                  CHECK (status IN ('NOWE','ZREALIZOWANE','ANULOWANE')),
  wartosc         NUMBER(12,2) DEFAULT 0 NOT NULL
);

CREATE TABLE pozycje_zamowien (
  id_zamowienia    NUMBER REFERENCES zamowienia(id_zamowienia),
  id_produktu      NUMBER REFERENCES typy_produktow(id_produktu),
  ilosc            NUMBER NOT NULL CHECK (ilosc > 0),
  cena_jednostkowa NUMBER(10,2) NOT NULL,   -- lokalna cena z chwili sprzeda¿y
  PRIMARY KEY (id_zamowienia, id_produktu)
);

CREATE TABLE rezerwacje (
  id_rezerwacji   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sklep           CHAR(3) DEFAULT 'WRO' NOT NULL CHECK (sklep = 'WRO'),
  sklep_zlecajacy CHAR(3) NOT NULL CHECK (sklep_zlecajacy IN ('WRO','WAW')),
  klient          VARCHAR2(100 CHAR),
  id_produktu     NUMBER NOT NULL REFERENCES typy_produktow(id_produktu),
  ilosc           NUMBER NOT NULL CHECK (ilosc > 0),
  status          VARCHAR2(20) DEFAULT 'AKTYWNA' NOT NULL
                  CHECK (status IN ('AKTYWNA','ZREALIZOWANA','ANULOWANA')),
  data_utworzenia TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

